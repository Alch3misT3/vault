'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('vault', {
  status: () => ipcRenderer.invoke('vault:status'),
  create: (pw) => ipcRenderer.invoke('vault:create', pw),
  unlock: (pw) => ipcRenderer.invoke('vault:unlock', pw),
  unlockPasskey: (id, prf) => ipcRenderer.invoke('vault:unlock-passkey', id, prf),
  passkeys: () => ipcRenderer.invoke('passkeys:list'),
  passkeyBegin: (pw, name) => ipcRenderer.invoke('passkeys:begin', pw, name),
  passkeyFinish: (id, transports, prf) => ipcRenderer.invoke('passkeys:finish', id, transports, prf),
  passkeyCancel: () => ipcRenderer.invoke('passkeys:cancel'),
  passkeyRemove: (id) => ipcRenderer.invoke('passkeys:remove', id),
  sitePasskeys: () => ipcRenderer.invoke('passkeys:site-list'),
  sitePasskeyDelete: (id) => ipcRenderer.invoke('passkeys:site-delete', id),
  onSitePasskeys: (fn) => ipcRenderer.on('site-passkeys', () => fn()),
  save: (items) => ipcRenderer.invoke('vault:save', items),
  changePassword: (cur, next, items) => ipcRenderer.invoke('vault:change-password', cur, next, items),
  lock: () => ipcRenderer.invoke('vault:lock'),
  purge: () => ipcRenderer.invoke('app:purge'),
  resume: () => ipcRenderer.invoke('vault:resume'),
  activity: () => ipcRenderer.invoke('app:activity'),
  note: (text) => ipcRenderer.invoke('app:note', text),
  takeNote: () => ipcRenderer.invoke('app:take-note'),
  copy: (text, secret) => ipcRenderer.invoke('clip:copy', text, secret),
  open: (url) => ipcRenderer.invoke('open:url', url),
  changePage: (id) => ipcRenderer.invoke('pw:change-page', id),
  breachCheck: () => ipcRenderer.invoke('breach:check'),
  ui: () => ipcRenderer.invoke('vault:ui'),
  saveUi: (key, value) => ipcRenderer.invoke('vault:ui-save', key, value),
  appPrefs: () => ipcRenderer.invoke('app:prefs'),
  setPref: (key, value) => ipcRenderer.invoke('app:set-pref', key, value),
  showQuick: () => ipcRenderer.invoke('app:quick'),
  showVaultFile: () => ipcRenderer.invoke('app:show-file'),
  logos: (domains) => ipcRenderer.invoke('logos:get', domains),
  onLogos: (fn) => ipcRenderer.on('logos', (_e, update) => fn(update)),
  pickImport: () => ipcRenderer.invoke('file:pick-import'),
  exportFile: (kind, contents, pw) => ipcRenderer.invoke('file:export', kind, contents, pw),
  restore: () => ipcRenderer.invoke('file:restore'),
  checkUpdates: () => ipcRenderer.invoke('update:check'),
  updateState: () => ipcRenderer.invoke('update:state'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdate: (fn) => ipcRenderer.on('update', (_e, st) => fn(st)),
  onMenu: (fn) => ipcRenderer.on('menu', (_e, cmd) => fn(cmd)),
  onLocked: (fn) => ipcRenderer.on('locked', () => fn()),
  onUnlocked: (fn) => ipcRenderer.on('unlocked-elsewhere', (_e, items) => fn(items)),
  bridgeState: () => ipcRenderer.invoke('bridge:state'),
  bridgePair: () => ipcRenderer.invoke('bridge:pair'),
  bridgeCancel: () => ipcRenderer.invoke('bridge:cancel'),
  bridgeRemove: (id) => ipcRenderer.invoke('bridge:remove', id),
  bridgeFolder: () => ipcRenderer.invoke('bridge:folder'),
  onBridge: (fn) => ipcRenderer.on('bridge', (_e, st) => fn(st)),
  onActivity: (fn) => ipcRenderer.on('activity', () => fn()),
});
